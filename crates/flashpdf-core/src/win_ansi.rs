use crate::RenderError;

pub(crate) fn encode(character: char) -> Result<u8, RenderError> {
    let byte = match character {
        ' '..='~' | '\u{00a0}'..='\u{00ff}' => character as u8,
        '\u{20ac}' => 128,
        '\u{201a}' => 130,
        '\u{0192}' => 131,
        '\u{201e}' => 132,
        '\u{2026}' => 133,
        '\u{2020}' => 134,
        '\u{2021}' => 135,
        '\u{02c6}' => 136,
        '\u{2030}' => 137,
        '\u{0160}' => 138,
        '\u{2039}' => 139,
        '\u{0152}' => 140,
        '\u{017d}' => 142,
        '\u{2018}' => 145,
        '\u{2019}' => 146,
        '\u{201c}' => 147,
        '\u{201d}' => 148,
        '\u{2022}' => 149,
        '\u{2013}' => 150,
        '\u{2014}' => 151,
        '\u{02dc}' => 152,
        '\u{2122}' => 153,
        '\u{0161}' => 154,
        '\u{203a}' => 155,
        '\u{0153}' => 156,
        '\u{017e}' => 158,
        '\u{0178}' => 159,
        _ => return Err(RenderError::UnsupportedCharacter(character)),
    };
    Ok(byte)
}

pub(crate) fn valid(text: &str) -> bool {
    text.chars()
        .all(|character| matches!(character, '\t'..='\r') || encode(character).is_ok())
}

pub(crate) fn decode(byte: u8) -> Option<char> {
    Some(match byte {
        32..=126 | 160..=255 => char::from(byte),
        128 => '\u{20ac}',
        130 => '\u{201a}',
        131 => '\u{0192}',
        132 => '\u{201e}',
        133 => '\u{2026}',
        134 => '\u{2020}',
        135 => '\u{2021}',
        136 => '\u{02c6}',
        137 => '\u{2030}',
        138 => '\u{0160}',
        139 => '\u{2039}',
        140 => '\u{0152}',
        142 => '\u{017d}',
        145 => '\u{2018}',
        146 => '\u{2019}',
        147 => '\u{201c}',
        148 => '\u{201d}',
        149 => '\u{2022}',
        150 => '\u{2013}',
        151 => '\u{2014}',
        152 => '\u{02dc}',
        153 => '\u{2122}',
        154 => '\u{0161}',
        155 => '\u{203a}',
        156 => '\u{0153}',
        158 => '\u{017e}',
        159 => '\u{0178}',
        _ => return None,
    })
}
