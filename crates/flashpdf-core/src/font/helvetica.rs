/// Pair kerning in 1/1000 em from the KPX pairs of Adobe's Helvetica and
/// Helvetica-Bold AFM files, which the obliques repeat. Each glyph name maps to
/// every WinAnsi code that shows it, space excluded. The right codes of each
/// left code sit at `STARTS` in `RIGHTS`; `PAIRS` picks the pair's regular and
/// bold values from `KERNS`.
pub(crate) fn kern(bold: bool, left: u8, right: u8) -> i16 {
    let Ok(row) = LEFTS.binary_search(&left) else {
        return 0;
    };
    let start = usize::from(STARTS[row]);
    RIGHTS[start..usize::from(STARTS[row + 1])]
        .binary_search(&right)
        .map_or(0, |index| {
            KERNS[usize::from(PAIRS[start + index])][usize::from(bold)]
        })
}

